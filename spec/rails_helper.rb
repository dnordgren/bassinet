# Ensures that the test database schema matches the current schema file.
# If there are pending migrations it will invoke `db:test:prepare` to
# recreate the test database by loading the schema.
# If you are not using ActiveRecord, you can remove these lines.
begin
  ActiveRecord::Migration.maintain_test_schema!
rescue ActiveRecord::PendingMigrationError => e
  abort e.to_s.strip
end
# This app has no domain schema in ActiveRecord — DynamoDB owns all records —
# so there is no schema to maintain. ActiveRecord is present only so the Solid
# gems can load; the test environment uses the :test cable adapter and does not
# touch SQLite.
RSpec.configure do |config|
  # No AR fixtures; there is no AR-backed model in this app.
  config.use_transactional_fixtures = false

  config.expect_with :rspec do |expectations|
    expectations.include_chain_clauses_in_custom_matcher_descriptions = true
  end

  config.mock_with :rspec do |mocks|
    mocks.verify_partial_doubles = true
  end

  config.shared_context_metadata_behavior = :apply_to_host_groups
  config.filter_run_when_matching :focus
  config.disable_monkey_patching!
  config.example_status_persistence_file_path = "tmp/rspec-status.txt"
  config.order = :defined
end

